// Package dnsmasq generates the dnsmasq fragment that feeds snake's ipsets in
// real time and pins policy domains to resolvers reached through the tunnel.
package dnsmasq

import (
	"fmt"
	"os"
	"strings"

	"github.com/irisariuan/snake/internal/config"
	"github.com/irisariuan/snake/internal/netfilter"
)

// chunk keeps dnsmasq lines comfortably below its line-length limit.
const chunk = 12

// Generate renders the dnsmasq configuration fragment. inspector tells
// whether the DNS inspector is running; without it, plain suffix rules are
// emitted even for policies with exclusions (which then cannot be honoured).
func Generate(c *config.Config, inspector bool) string {
	var b strings.Builder
	b.WriteString("# Generated by snake. Do not edit; changes are overwritten.\n")
	anyDoH := c.DoHBlockedAnywhere()
	for _, p := range c.Policies {
		if !p.Enabled {
			continue
		}
		if !p.HasDomains() && !p.HasDrops() {
			continue
		}
		rules := p.DomainRules()
		fmt.Fprintf(&b, "# policy %d: %s\n", p.ID, p.Name)
		sets := netfilter.SetName(p.ID, netfilter.KindDomain, false) + "," +
			netfilter.SetName(p.ID, netfilter.KindDomain, true)
		// Plain suffix rules are matched by dnsmasq itself (works even when
		// the daemon is down); wildcards, regexes, keywords, exclusions and
		// CNAME chains are handled by the DNS inspector.
		native := rules.NativeSuffixes()
		if !inspector {
			native = rules.PlainSuffixes()
		}
		if p.HasDomains() {
			for _, part := range chunks(native) {
				fmt.Fprintf(&b, "ipset=/%s/%s\n", strings.Join(part, "/"), sets)
			}
		}
		// Plain drop: rules fill the drop sets the same way (a drop beats
		// include rules, so extra drop entries are always correct).
		drops := netfilter.SetName(p.ID, netfilter.KindDrop, false) + "," + netfilter.SetName(p.ID, netfilter.KindDrop, true)
		for _, part := range chunks(rules.DropSuffixes(!inspector)) {
			fmt.Fprintf(&b, "ipset=/%s/%s\n", strings.Join(part, "/"), drops)
		}
		if p.Leak.DNSViaTunnel && p.Leak.DNSServer != "" {
			// DoT/DoH: snake's local forwarder encrypts the query and
			// sends it to the resolver through the tunnel.
			upstream := p.Leak.DNSServer
			if p.Leak.Encrypted() {
				upstream = c.Settings.DNSForwardAddr(p.ID)
			}
			for _, part := range chunks(rules.Bases()) {
				fmt.Fprintf(&b, "server=/%s/%s\n", strings.Join(part, "/"), upstream)
			}
		}
	}
	if anyDoH {
		b.WriteString("# DoH resolvers\n")
		for _, part := range chunks(netfilter.DefaultDoHDomains) {
			fmt.Fprintf(&b, "ipset=/%s/%s,%s\n", strings.Join(part, "/"), netfilter.DoHSet4, netfilter.DoHSet6)
		}
		if c.Settings.DoHCanary {
			b.WriteString("# canaries: NXDOMAIN tells Firefox / iCloud Private Relay to stand down\n")
			for _, d := range netfilter.CanaryDomains {
				fmt.Fprintf(&b, "local=/%s/\n", d)
			}
		}
	}
	return b.String()
}

func chunks(in []string) [][]string {
	var out [][]string
	for len(in) > 0 {
		n := chunk
		if len(in) < n {
			n = len(in)
		}
		out = append(out, in[:n])
		in = in[n:]
	}
	return out
}

// PostConf appends the conf-file include to dnsmasq's main config (called from
// /jffs/scripts/dnsmasq.postconf with the config path).
func PostConf(mainConf, fragment string) error {
	b, err := os.ReadFile(mainConf)
	if err != nil {
		return err
	}
	line := "conf-file=" + fragment
	if strings.Contains(string(b), line) {
		return nil
	}
	f, err := os.OpenFile(mainConf, os.O_APPEND|os.O_WRONLY, 0o644)
	if err != nil {
		return err
	}
	defer f.Close()
	_, err = f.WriteString("\n" + line + "\n")
	return err
}
