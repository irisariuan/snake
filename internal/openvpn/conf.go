// Package openvpn checks OpenVPN client configurations (.ovpn files) and
// runs the OpenVPN clients snake manages itself, beyond the firmware's.
package openvpn

import (
	"fmt"
	"strings"
)

// Conf is a client configuration, cleaned of everything snake controls.
type Conf struct {
	lines     []string // kept directives and inline blocks, in order
	NeedsAuth bool     // auth-user-pass: the server asks for a username and password
	Remotes   []string // "host port" of each remote, for display
}

// Directives snake sets itself or that would change the router: the
// interface, routing, DNS, scripts, daemon, logging and management.
var dropped = map[string]bool{
	"dev": true, "dev-type": true, "dev-node": true,
	"route": true, "route-ipv6": true, "redirect-gateway": true, "redirect-private": true,
	"route-nopull": true, "route-noexec": true, "route-delay": true, "route-method": true,
	"dhcp-option": true, "block-outside-dns": true, "register-dns": true,
	"up": true, "down": true, "route-up": true, "route-pre-down": true, "ipchange": true,
	"tls-verify": true, "learn-address": true, "client-connect": true, "client-disconnect": true,
	"auth-user-pass-verify": true, "plugin": true, "script-security": true, "up-restart": true, "down-pre": true,
	"daemon": true, "log": true, "log-append": true, "syslog": true, "writepid": true, "status": true,
	"management": true, "management-query-passwords": true, "management-hold": true, "management-client": true,
	"user": true, "group": true, "chroot": true, "cd": true,
	"auth-user-pass": true, "askpass": true, "pull-filter": true,
	"persist-tun": true, "auth-nocache": true,
}

// Directives whose argument is a file: the router does not have it, the
// contents must be pasted inline (<ca>...</ca>).
var fileArgs = map[string]bool{
	"ca": true, "cert": true, "key": true, "tls-auth": true, "tls-crypt": true, "tls-crypt-v2": true,
	"pkcs12": true, "secret": true, "extra-certs": true, "crl-verify": true, "dh": true,
	"http-proxy-user-pass": true,
}

// Parse checks an .ovpn client configuration.
func Parse(text string) (*Conf, error) {
	c := &Conf{}
	client, inBlock := false, ""
	for n, raw := range strings.Split(strings.ReplaceAll(text, "\r\n", "\n"), "\n") {
		line := strings.TrimSpace(raw)
		if inBlock != "" {
			c.lines = append(c.lines, line)
			if strings.EqualFold(line, "</"+inBlock+">") {
				inBlock = ""
			}
			continue
		}
		if line == "" || line[0] == '#' || line[0] == ';' {
			continue
		}
		if strings.HasPrefix(line, "<") && strings.HasSuffix(line, ">") && !strings.HasPrefix(line, "</") {
			inBlock = strings.ToLower(strings.Trim(line, "<>"))
			if inBlock == "auth-user-pass" {
				return nil, fmt.Errorf("line %d: enter the username and password in the fields, not inline", n+1)
			}
			c.lines = append(c.lines, line)
			continue
		}
		f := strings.Fields(line)
		key := strings.ToLower(strings.TrimPrefix(f[0], "--"))
		bad := func(format string, a ...any) error {
			return fmt.Errorf("line %d: %s", n+1, fmt.Sprintf(format, a...))
		}
		switch {
		case key == "auth-user-pass":
			c.NeedsAuth = true
			continue
		case key == "dev" && len(f) > 1 && strings.HasPrefix(strings.ToLower(f[1]), "tap"),
			key == "dev-type" && len(f) > 1 && strings.EqualFold(f[1], "tap"):
			return nil, bad("tap (bridged) tunnels are not supported, only tun")
		case dropped[key]:
			continue
		case fileArgs[key] && len(f) > 1 && !strings.EqualFold(f[1], "[inline]"):
			return nil, bad("%s refers to the file %q: paste its contents inline as <%s>...</%s>", key, f[1], key, key)
		case key == "server", key == "mode" && len(f) > 1 && f[1] == "server", key == "tls-server":
			return nil, bad("this is a server configuration; snake needs a client one")
		case key == "client", key == "pull", key == "tls-client":
			client = true
		case key == "remote":
			if len(f) < 2 {
				return nil, bad("remote needs a host")
			}
			c.Remotes = append(c.Remotes, strings.Join(f[1:min(len(f), 3)], " "))
		}
		c.lines = append(c.lines, line)
	}
	switch {
	case inBlock != "":
		return nil, fmt.Errorf("<%s> is not closed", inBlock)
	case len(c.Remotes) == 0:
		return nil, fmt.Errorf("needs a remote line (the VPN server)")
	case !client:
		return nil, fmt.Errorf("needs a client line: this does not look like a client configuration")
	}
	return c, nil
}

// Render returns the configuration snake runs: the provider's directives,
// then snake's own, which come last and so win. Pushed routes and DNS
// are ignored: snake's policy tables route into the tunnel.
func (c *Conf) Render(dev, credsFile, pidFile string) string {
	var b strings.Builder
	b.WriteString("# generated by snake from the saved configuration\n")
	for _, l := range c.lines {
		b.WriteString(l + "\n")
	}
	b.WriteString("\n# snake\n")
	fmt.Fprintf(&b, "dev %s\ndev-type tun\n", dev)
	b.WriteString("route-nopull\npull-filter ignore \"redirect-gateway\"\npull-filter ignore \"dhcp-option\"\npull-filter ignore \"block-outside-dns\"\n")
	b.WriteString("script-security 1\npersist-tun\nauth-nocache\n")
	if credsFile != "" {
		b.WriteString("auth-user-pass " + credsFile + "\n")
	}
	b.WriteString("writepid " + pidFile + "\n")
	return b.String()
}
